/*========================================================================
/*========================================================================
 * 文件名：account.h
 * 功  能：账号模块的头文件。声明用户结构体类型 User，以及注册、登录、
 *         密码安全检测三个对外函数。
 * 说  明：按照小组约定，账号信息用“结构体数组”保存（不采用链表）。
 *         头文件只放声明，函数的具体实现见 account.c。
 *========================================================================*/
#ifndef ACCOUNT_H              /* 防止本头文件被重复包含 */
#define ACCOUNT_H

#define NAME_MAX     32       /* 用户名字符数组长度：31 个字符 + 结束符 '\0' */
#define PASSWORD_MAX 64       /* 密码字符数组长度：63 个字符 + 结束符 '\0'   */
#define USER_MAX     100      /* 一次最多读入内存的账号个数                  */

/*------------------------------------------------------------------------
 * 结构体：User
 * 用  途：保存一个用户的登录信息，与 users.txt 中的一行记录一一对应。
 *------------------------------------------------------------------------*/
typedef struct
{
    char name[NAME_MAX];          /* 用户名，不含空白字符，最长 31 字节 */
    char password[PASSWORD_MAX];  /* 登录密码，最长 63 字节             */
} User;

/*------------------------------------------------------------------------
 * 函数：checkPassword
 * 功  能：对用户输入的密码做安全强度检测。
 * 参  数：password —— 待检测的密码字符串（以 '\0' 结尾）。
 * 返  回：0 表示不安全（长度小于 6 位，或字符种类只有一类）；
 *         1 表示中度安全（字符种类为两类）；
 *         2 表示安全（字符种类为三类及以上）。
 *         数字、大写字母、小写字母、其它符号算作四类不同的字符。
 *------------------------------------------------------------------------*/
int checkPassword(char password[]);

/*------------------------------------------------------------------------
 * 函数：registerUser
 * 功  能：把新用户写入账号文件 users.txt（首次运行会自动建立该文件）。
 * 参  数：user —— 待注册的用户（用户名和密码均已由调用者填好）。
 * 返  回：1 表示注册成功；0 表示用户名重复、参数为空或文件操作失败。
 * 说  明：注册成功后由调用者（main.c）返回登录入口。
 *------------------------------------------------------------------------*/
int registerUser(User user);

/*------------------------------------------------------------------------
 * 函数：loginUser
 * 功  能：在账号文件中查找用户名和密码都相同的记录。
 * 参  数：user —— 待验证的用户（用户名和密码均已由调用者填好）。
 * 返  回：1 表示两项都匹配，登录成功；0 表示用户名不存在或密码错误。
 *------------------------------------------------------------------------*/
int loginUser(User user);

#endif /* ACCOUNT_H */
