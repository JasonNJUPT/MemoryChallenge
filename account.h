/*========================================================================
 * 文件名：account.h
 * 功  能：账号模块的头文件。定义用户结构体 User，并声明登录页、注册页
 *         需要的三个页面函数：resetAccountPage、updateAccountPage、
 *         drawAccountPage
 * 说  明：按小组约定，账号仍然用“结构体数组”保存，不使用链表
 *         本头文件只对外公开这三个页面函数；密码检测、注册写入、登录
 *         校验等细节都留在 account.c 内部，用 static 修饰，调用方无需关心
 *         图形版的页面由 main.c 调度：进入页面前调 reset，之后每帧先调
 *         update 处理输入，再调 draw 绘制
 *========================================================================*/
#ifndef ACCOUNT_H  // 防止本头文件被重复包含
#define ACCOUNT_H

#include "raylib.h"  // 页面函数要用到 Font 类型

#define NAME_MAX     32  // 用户名字符数组长度：31 个字符 + 结束符 '\0'
#define PASSWORD_MAX 64  // 密码字符数组长度：63 个字符 + 结束符 '\0'

/*------------------------------------------------------------------------
 * 结构体：User
 * 用  途：保存一个用户的登录信息，与 users.txt 中的一行记录一一对应
 *------------------------------------------------------------------------*/
typedef struct
{
    char name[NAME_MAX];  // 用户名，最多 31 字节，不含空白字符
    char password[PASSWORD_MAX];  // 登录密码，最多 63 字节，不含空白字符
} User;

/*------------------------------------------------------------------------
 * 函数：resetAccountPage
 * 功  能：准备登录页或注册页，把页面恢复成刚进入时的样子
 * 输  入：registerMode 为 0 显示登录页，为 1 显示注册页
 * 输  出：清空用户名、密码两个输入框，焦点回到用户名框，清除提示文字
 *         和“等待弱密码确认”的状态。不在这个函数里读写账号文件
 * 返回值：无
 *------------------------------------------------------------------------*/
void resetAccountPage(int registerMode);

/*------------------------------------------------------------------------
 * 函数：updateAccountPage
 * 功  能：处理这一帧的键盘输入（输入字符、退格、Tab 换焦点、回车提交）
 *         和鼠标点击（切换输入框、点按钮），完成一次登录或注册
 * 输  入：user 是接收登录账号的结构体地址，由 main.c 提供
 * 输  出：只有登录成功时才把用户名和密码写入 *user；登录失败、注册成功、
 *         点返回等其它情况都不修改 *user
 * 返回值：0 表示留在账号页继续显示；1 表示登录成功，main.c 可以切到玩家
 *         菜单；2 表示用户点了“返回”，由 main.c 决定回到入口菜单
 * 说  明：本函数每帧只处理一次点击，不等待输入，不结束程序
 *------------------------------------------------------------------------*/
int updateAccountPage(User *user);

/*------------------------------------------------------------------------
 * 函数：drawAccountPage
 * 功  能：把账号页画出来，包括标题、两个输入框、按钮、密码强度提示和
 *         页面底部的操作提示
 * 输  入：font 是已经加载好中文字形的字体，由 main.c 传入，本模块不重复
 *         加载字体
 * 输  出：只向屏幕绘制内容，不读写账号文件，不修改账号状态
 * 返回值：无
 *------------------------------------------------------------------------*/
void drawAccountPage(Font font);

#endif  // ACCOUNT_H
