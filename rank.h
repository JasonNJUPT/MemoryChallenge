#ifndef RANK_H
#define RANK_H

/*==============================================================
  rank.h --- 成绩排行模块对外接口（任务 C）

  约定：
    level   取值 1、2、3，分别代表 初级 / 中级 / 高级；
            只有模块内部访问数组时才减 1。
    seconds 是一局的通关用时（秒），不能小于 0；
            0 秒可表示不足一秒的通关；退出由 playGame 返回值表示。
    榜单    每个级别各自保存前五名，共 3 x 5 = 15 条。
    文件    ranks.txt，纯文本，一行一条：级别 用户名 秒数
            例如：2 player1 38
==============================================================*/

#define RANK_LEVELS 3       /* 级别个数 */
#define RANK_TOP    5       /* 每级保留前几名 */
#define RANK_NAME   32      /* 用户名缓冲区（31 字节 + '\0'） */
#define RANK_FILE   "ranks.txt"

/*--------------------------------------------------------------
  提交一次成绩。

  参数：name    用户名（不超过 31 字节，不含空白）
        level   难度 1/2/3
        seconds 用时（秒，必须 >= 0）

  返回： 1  成绩已进入前五，并成功写入文件
         0  没有刷新（同名玩家的旧成绩更快，或两次相同），
            或者榜已满且本次成绩比第五名慢
        -1  参数非法，或文件读写失败
--------------------------------------------------------------*/
int saveScore(const char name[], int level, int seconds);

/*--------------------------------------------------------------
  在屏幕上打印某一级别的前五名。
  参数 level 取 1/2/3；空榜打印"暂无成绩"。
--------------------------------------------------------------*/
void showRank(int level);

/* 查询是否存在成绩：1 有成绩，0 空榜，-1 文件读取失败。 */
int hasRankData(void);

#endif
